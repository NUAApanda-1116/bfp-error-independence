"""Generate a concise LS application from retained CSV evidence, without sampling."""
from pathlib import Path
import csv

BASE = Path(__file__).resolve().parent


def main():
    with (BASE / 'experiments/least_squares_results.csv').open(
            encoding='utf-8', newline='') as stream:
        rows = list(csv.DictReader(stream))
    intercept = next(r for r in rows if r['distribution'] == 'lognormal'
                     and r['coordinate'] == 'intercept')
    with (BASE / 'experiments/least_squares_precision.csv').open(
            encoding='utf-8', newline='') as stream:
        precision = list(csv.DictReader(stream))
    ln = {int(r['L']): r for r in precision if r['distribution'] == 'lognormal'}
    section = r'''% Generated by revision/compact_application.py from retained CSV evidence.
\subsection{Fixed-design least squares with a quantized right-hand side}
\label{sec:revision-ls}
Let $A\in\mathbb R^{n\times p}$ be deterministic with full column rank,
$b_i$ be i.i.d., and $\theta=A^\dagger b$, where
$A^\dagger=(A^TA)^{-1}A^T$. Compressing $b$ as one block gives
$\delta\theta=A^\dagger(Q(b)-b)$, the additional coefficient error for
the same observations.
\begin{corollary}[Coefficient error and the constant direction]
\label{cor:revision-ls}
With $g=A^\dagger\mathbf1$,
\begin{align}
 \mathbb E[\delta\theta]&=\mu g,\qquad
 \operatorname{Cov}(\delta\theta)
 =(v-\kappa)(A^TA)^{-1}+\kappa gg^T,\label{eq:revision-ls-cov}\\
 \mathbb E[\|\delta\theta\|_2^2]
 &=(v-\kappa)\operatorname{tr}((A^TA)^{-1})
       +(\kappa+\mu^2)\|g\|_2^2.\label{eq:revision-ls-mse}
\end{align}
For $A=[\mathbf1,Z]$, $g=(1,0,\ldots,0)^T$; for $A^T\mathbf1=0$, $g=0$.
\end{corollary}
\begin{proof}
Multiply \eqref{eq:revision-spectrum} by $A^\dagger$ and its transpose,
use $A^\dagger(A^\dagger)^T=(A^TA)^{-1}$, and add the squared mean
to the covariance trace. The two cases follow from the action on $\mathbf1$.
\end{proof}
The common component and bias therefore enter the intercept, while a
centered slope depends on $v-\kappa$. For $n=128$, we fit
$\alpha+\beta(t_i-1/2)$ and $\gamma t_i$, with $t_i=(i-1)/(n-1)$,
to either Exp$(1)$ or $\exp(N(0,1))$ observations. Each law uses
$80\,000$ independent right-hand sides and $400$ whole-block bootstrap
replicates; the fixed QR operators are applied in binary64.
At $L=2$, dropping $\kappa$ while retaining the exact marginal bias and
variance underpredicts the lognormal intercept variance by a factor
__VAR_RATIO__. The full coefficient mean, variance, and MSE results
cover $6$, $5$, and $5$ of $6$ population predictions, respectively;
the exponential centered-slope interval miss is retained in the package.

The intercept has compression MSE $[v+(n-1)\kappa]/n+\mu^2$.
In the retained $L=2,3,4,5$ sweep, an illustrative RMS tolerance $0.10$
was chosen after the initial application and analytic inspection.
For lognormal inputs the exact model selects $L=4$; the bias-aware
independent model selects $L=3$; independent uniform-cell noise selects
$L=2$. Their measured RMS errors are __RMS4__, __RMS3__, and __RMS2__,
respectively, so the latter two choices miss the tolerance. Every tested
precision and its interval is retained in the package. This example
illustrates an accuracy decision for i.i.d. compressed observations;
the following experiment also accounts for scale-storage cost.
'''
    section = section.replace('__VAR_RATIO__', f"{float(intercept['exact_variance_ratio']):.2f}")
    for level in (2, 3, 4):
        section = section.replace(f'__RMS{level}__', f"{float(ln[level]['mc_rms']):.5f}")
    (BASE / 'application_compact.tex').write_text(section, encoding='utf-8')
    print('Generated concise LS section from saved results.')


if __name__ == '__main__':
    main()
